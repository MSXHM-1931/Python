import math

# A君：每天进步 1%，365 天
A_factor = 1.01 ** 365

# B君：每周 5 天工作、2 天休息，休息日下降 1%
# 设工作日努力参数为 r，满足
# (1 + r)^5 * 0.99^2 = 1.01^7  (按 7 天为一个周期)
# 因此：
r_week = (1.01 ** 7 / 0.99 ** 2) ** (1 / 5) - 1

# 也可以直接按 365 天的整体效果计算（按年末多出 1 天视为工作日）
# 261 个工作日、104 个休息日
r_exact_work = (A_factor / (0.99 ** 104)) ** (1 / 261) - 1

# 若把年末多出的一天视为休息日，则为：
# 260 个工作日、105 个休息日
r_exact_rest = (A_factor / (0.99 ** 105)) ** (1 / 260) - 1

print(f"A君年终增长系数：{A_factor:.6f}")
print(f"按 7 天周期，B 君工作日需努力约：{r_week * 100:.4f}%")
print(f"按 365 天实际日历（多出 1 天当作工作日）：{r_exact_work * 100:.4f}%")
print(f"按 365 天实际日历（多出 1 天当作休息日）：{r_exact_rest * 100:.4f}%")

# 结论：工作日的努力参数约为 1.81%
print("结论：B君的工作日努力参数约为 1.81%，才可与 A 君“每天努力 1%”的效果相当。")